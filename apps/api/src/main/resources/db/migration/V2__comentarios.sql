CREATE TABLE comentario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  demanda_id BIGINT NOT NULL REFERENCES demanda(id) ON DELETE CASCADE,
  autor_id BIGINT NOT NULL REFERENCES usuario(id),
  texto TEXT NOT NULL DEFAULT '',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX comentario_demanda_recente_idx ON comentario(demanda_id, criado_em DESC, id DESC);

CREATE TABLE comentario_imagem (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comentario_id BIGINT NOT NULL REFERENCES comentario(id) ON DELETE CASCADE,
  nome VARCHAR(255) NOT NULL,
  tipo VARCHAR(100) NOT NULL,
  tamanho BIGINT NOT NULL,
  caminho VARCHAR(255) NOT NULL UNIQUE
);
