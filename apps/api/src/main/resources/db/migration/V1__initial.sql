CREATE TABLE usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login VARCHAR(40) NOT NULL UNIQUE,
  nome VARCHAR(100) NOT NULL,
  senhahash VARCHAR(255) NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE demanda (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(180) NOT NULL,
  descricao TEXT NOT NULL DEFAULT '',
  status VARCHAR(40) NOT NULL DEFAULT 'AGUARDANDO_DESENVOLVIMENTO',
  responsavel_id BIGINT REFERENCES usuario(id),
  criado_por_id BIGINT NOT NULL REFERENCES usuario(id),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  versao BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT demanda_status_check CHECK (status IN ('AGUARDANDO_DESENVOLVIMENTO','EM_DESENVOLVIMENTO','DESENVOLVIMENTO_EM_PROGRESSO','EM_TESTE','REABERTA'))
);
CREATE INDEX demanda_status_idx ON demanda(status);
CREATE INDEX demanda_responsavel_idx ON demanda(responsavel_id);
CREATE INDEX demanda_atualizado_idx ON demanda(atualizado_em DESC);

CREATE TABLE anexo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  demanda_id BIGINT NOT NULL REFERENCES demanda(id) ON DELETE CASCADE,
  nome VARCHAR(255) NOT NULL,
  tipo VARCHAR(100) NOT NULL,
  tamanho BIGINT NOT NULL,
  caminho VARCHAR(255) NOT NULL UNIQUE,
  enviado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE filtro (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
  nome VARCHAR(80) NOT NULL,
  texto VARCHAR(180),
  status VARCHAR(40),
  responsavel_id BIGINT REFERENCES usuario(id),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (usuario_id, nome)
);
